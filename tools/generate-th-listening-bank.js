const out = {};
for (const item of lb.items) {
  const mode = item.mode || '';
  const level = item.level || '';
  const char = item.pedagogy?.character || '';
  const orig_q = item.question || '';
  const orig_exp = item.explain || '';
  const opts = item.options || [];
  const ans_idx = item.answerIndex ?? 0;
  
  const q_th = translateQuestion(orig_q, char);
  let opts_th = null;
  if (Array.isArray(opts) && opts.length > 0) {
    if (mode === 'paraphrase' || ['B1', 'B2', 'C1', 'C2'].includes(level)) {
      opts_th = opts.slice();
    } else {
      opts_th = opts.map(o => translateSentence(o));
    }
  }
  
  const correct_opt = (opts_th && ans_idx >= 0 && ans_idx < opts_th.length) ? opts_th[ans_idx] : '';
  const quote = correct_opt ? `“${correct_opt}”` : '';
  
  let exp_th = '';
  if (mode === 'gist') {
    exp_th = char ? `ตลอดเสียง ${char} พูดถึงเรื่องนี้เป็นหลัก — ดังนั้นคำตอบที่ถูกต้องคือ: ${quote}.` : `ตลอดเสียงพูดถึงเรื่องนี้เป็นหลัก — ดังนั้นคำตอบที่ถูกต้องคือ: ${quote}.`;
  } else if (mode === 'detail') {
    exp_th = `รายละเอียดนี้ระบุไว้โดยตรงในเสียง: ${quote}.`;
  } else if (mode === 'inference') {
    exp_th = `คำตอบนี้ไม่ได้พูดออกมาโดยตรง แต่เบาะแสในเสียงนำไปสู่ข้อสรุป: ${quote}.`;
  } else if (mode === 'attitude') {
    exp_th = char ? `การเลือกใช้คำและน้ำเสียงของ ${char} ในเสียงแสดงให้เห็นว่า: ${quote}.` : `การเลือกใช้คำและน้ำเสียงแสดงให้เห็นว่า: ${quote}.`;
  } else if (mode === 'paraphrase') {
    exp_th = `ในเสียง ประโยคที่ยกมาในโจทย์สื่อความหมายเหมือนกับ ${quote}.`;
  } else if (mode === 'dictation') {
    const m = orig_exp.match(/“([^”]+)”/);
    const txt = m ? m[1] : (item.answerText || '');
    exp_th = `ประโยคที่พูดในเสียงคือ: “${txt}”.`;
  } else {
    exp_th = translateSentence(orig_exp);
  }
  
  const entry = { question: q_th, explain: exp_th };
  if (opts_th) entry.options = opts_th;
  out[item.id] = entry;
}

