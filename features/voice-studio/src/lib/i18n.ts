export function vocabMeaningForLocale(
  locale: LearnerLocale,
  v: { id: string; term: string; meaningId: string; meaningTh?: string; exampleSentence?: string }
): string {
  if (locale === 'id') return v.meaningId;
  if (locale === 'th') return v.meaningTh && v.meaningTh !== v.meaningId ? v.meaningTh : (VOCAB_PREREQ_EN[v.id] || v.meaningId);
  if (VOCAB_PREREQ_EN[v.id]) return VOCAB_PREREQ_EN[v.id];
  // Structured JA/ZH items often look like "atatameru - menghangatkan": strip Indonesian half so non-ID gets clean reading
  const raw = String(v.meaningId || '').trim();
  const dashIdx = raw.indexOf(' - ');
  if (dashIdx > 0 && raw.slice(0, dashIdx).trim() && raw.slice(0, dashIdx).trim() !== v.term) {
    return raw.slice(0, dashIdx).trim();
  }
  return v.exampleSentence || v.term;
}

export function scenarioMetaForLocale(
  locale: LearnerLocale,
  scen: {
    id: string;
    titleId: string;
    titleTh: string;
    situationId: string;
    situationTh: string;
    competencyNameId: string;
    competencyNameTh: string;
    openingLine?: string;
    openingTranslationId?: string;
    openingTranslationTh?: string;
    missionGoalsId?: string[];
    missionGoalsTh?: string[];
    level?: string;
  }
): {
  title: string;
  situation: string;
  competency: string;
  openingTranslation: string;
  missionGoals: string[];
} {
  if (locale === 'id') {
    return {
      title: scen.titleId,
      situation: scen.situationId,
      competency: scen.competencyNameId,
      openingTranslation: scen.openingTranslationId || '',
      missionGoals: scen.missionGoalsId || [],
    };
  }
  if (locale === 'th') {
    return {
      title: scen.titleTh && scen.titleTh !== scen.titleId ? scen.titleTh : (SCENARIO_EN_META[scen.id]?.title || scen.titleId),
      situation: scen.situationTh && scen.situationTh !== scen.situationId ? scen.situationTh : (SCENARIO_EN_META[scen.id]?.situation || scen.situationId),
      competency: scen.competencyNameTh || scen.competencyNameId,
      openingTranslation: scen.openingTranslationTh || SCENARIO_EN_META[scen.id]?.openingTranslation || '',
      missionGoals: scen.missionGoalsTh && scen.missionGoalsTh.join('|') !== (scen.missionGoalsId || []).join('|')
        ? scen.missionGoalsTh
        : (SCENARIO_EN_META[scen.id]?.missionGoals || scen.missionGoalsTh || []),
    };
  }
  const en = SCENARIO_EN_META[scen.id];
  if (en) {
    return {
      title: en.title,
      situation: en.situation,
      competency: en.competency,
      openingTranslation: en.openingTranslation || '',
      missionGoals: en.missionGoals || [],
    };
  }
  if (scen.id.startsWith('scen_ielts_cue_')) {
    const topic = scen.titleId.replace(/^IELTS Speaking:\s*/i, '');
    return {
      title: scen.titleId,
      situation: `Official Cambridge IELTS Speaking simulation (Part 2 Cue Card & Part 3 Discussion): ${topic}`,
      competency: scen.competencyNameId,
      openingTranslation: scen.openingLine || '',
      missionGoals: [
        'Speak coherently for 1–2 minutes covering every cue card point.',
        'Use academic discourse markers cleanly and naturally.',
      ],
    };
  }
  if (scen.id.startsWith('scen_ja_fiezel-life_')) {
    const topic = scen.titleId.replace(/^FIEZEL Japanese Life [^:]+:\s*/i, '');
    return {
      title: scen.titleId,
      situation: `FIEZEL Japanese Life conversation (${scen.level || 'A1'}): ${topic}`,
      competency: scen.competencyNameId.replace(/^Komunikasi Nyata:\s*/i, 'Real-Life Communication: '),
      openingTranslation: '',
      missionGoals: [
        'Use the situational Japanese sentence pattern naturally.',
        'Deliver clear pronunciation and polite phrasing smoothly.',
      ],
    };
  }
  return {
    title: scen.titleId,
    situation: scen.situationId,
    competency: scen.competencyNameId,
    openingTranslation: '',
    missionGoals: [],
  };
}

export function t(locale: LearnerLocale, key: string): string {
  if (locale === 'id') return COPY.id?.[key] ?? COPY.en?.[key] ?? key;
  return COPY[locale]?.[key] ?? COPY.en?.[key] ?? COPY.id?.[key] ?? key;
}

export function tMasteryState(locale: LearnerLocale, state: MasteryStateName): string {
  return t(locale, `state.${state}`);
}
